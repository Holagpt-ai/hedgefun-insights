#!/usr/bin/env node
/**
 * Deterministic MCP Edge validation. This is the release gate for the generated
 * bundle; standalone `deno check supabase/functions/mcp/index.ts` is not.
 *
 * Actual Lovable / repo pipeline (from @lovable.dev/mcp-js 0.20.0):
 *   1. Author TypeScript in src/lib/mcp/*.
 *   2. Vite plugin `@lovable.dev/mcp-js/stacks/supabase/vite` (`mcpPlugin`)
 *      esbuild-bundles that graph into supabase/functions/mcp/index.ts on
 *      `configResolved` / `buildStart` (also `vite` / `vite build`). Types are
 *      erased by design; the file is a Deno deployment artifact, not source.
 *      `mcpWindowsSafeEmitPlugin` then re-emits with a project-relative import
 *      so Windows does not collapse the graph (`C:\...` is not a POSIX `/` path).
 *   3. `lovable-mcp-extract-manifest` snapshots `.lovable/mcp/manifest.json`
 *      in Lovable's commit pipeline.
 *   4. `supabase functions deploy mcp` uploads the generated file; Edge Runtime
 *      bundles it. Neither the plugin, tsc (tsconfig.app.json includes `src`
 *      only), nor Supabase deploy run `deno check` on the emitted bundle.
 *
 * `deno check` on the generated file reports TS7006 implicit-any because the
 * official emit is type-erased JavaScript with a .ts extension. Type safety
 * is enforced on src/lib/mcp/* instead.
 *
 * Usage:
 *   node scripts/mcp-edge-validate.mjs
 *   node scripts/mcp-edge-validate.mjs --bundle-only
 */
import { execSync, spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { createServer } from "vite";
import { productionImportMetaEnv, syncMcpSupabaseFunction } from "./mcp-supabase-emit.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const BUNDLE = join(ROOT, "supabase/functions/mcp/index.ts");
const EXTRACT_BIN = join(ROOT, "node_modules/@lovable.dev/mcp-js/dist/cli/extract-manifest.js");

const GENERATED_BANNER =
  "// AUTO-GENERATED by @lovable.dev/mcp-js — do not edit. Regenerated by the Vite plugin.\n" +
  "// To take ownership, delete this banner line; the plugin then leaves the file alone.";

const TAKEOVER_MARKERS = [
  "ownership taken",
  "// @ts-nocheck — bundled output",
  "Generated from src/lib/mcp/index.ts by @lovable.dev/mcp-js; ownership taken",
];

const REQUIRED_TOOLS = ["search_stocks", "get_stock_quote", "get_market_movers", "get_market_news"];

function fail(message) {
  console.error(`mcp-edge-validate: ${message}`);
  process.exit(1);
}

function normalize(text) {
  return text.replace(/\r\n/g, "\n");
}

function sha256(text) {
  return createHash("sha256").update(normalize(text)).digest("hex");
}

function readBundle() {
  return readFileSync(BUNDLE, "utf8");
}

function assertGeneratorOwned(source, installedMcpJsVersion) {
  const text = normalize(source);
  if (!text.startsWith(GENERATED_BANNER)) {
    fail("generated bundle is missing the AUTO-GENERATED ownership banner");
  }
  if (text.startsWith("// @ts-nocheck")) {
    fail("generated bundle starts with @ts-nocheck; generator ownership was replaced");
  }
  for (const marker of TAKEOVER_MARKERS) {
    if (text.includes(marker)) {
      fail(`generated bundle contains unauthorized manual-ownership marker: ${marker}`);
    }
  }
  if (!text.includes("Deno.serve(createSupabaseHandler(")) {
    fail("generated bundle is missing the Supabase Edge Deno.serve entry");
  }
  for (const tool of REQUIRED_TOOLS) {
    if (!text.includes(`name: "${tool}"`)) {
      fail(`generated bundle is missing tool ${tool}`);
    }
  }
  const pins = [...text.matchAll(/@lovable\.dev\/mcp-js@([0-9]+\.[0-9]+\.[0-9]+)/g)].map((m) => m[1]);
  if (pins.length === 0) {
    fail("generated bundle has no @lovable.dev/mcp-js version pins");
  }
  if (new Set(pins).size !== 1 || pins[0] !== installedMcpJsVersion) {
    fail(`generated bundle mcp-js pins ${[...new Set(pins)].join(",")} !== installed ${installedMcpJsVersion}`);
  }
}

function runShell(command) {
  try {
    execSync(command, { cwd: ROOT, stdio: "inherit" });
  } catch {
    fail(`command failed: ${command}`);
  }
}

function gitDiff(paths) {
  const result = spawnSync("git", ["diff", "--", ...paths], {
    cwd: ROOT,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
    shell: false,
  });
  if (result.status !== 0) fail(`git diff failed: ${result.stderr}`);
  return result.stdout;
}

async function regenerateOnce() {
  const server = await createServer({
    configFile: join(ROOT, "vite.config.ts"),
    mode: "production",
    root: ROOT,
    logLevel: "silent",
    server: { middlewareMode: true, hmr: false, watch: null },
    optimizeDeps: { noDiscovery: true },
  });
  await server.close();
}

async function validateBundle() {
  const installed = JSON.parse(
    readFileSync(join(ROOT, "node_modules/@lovable.dev/mcp-js/package.json"), "utf8"),
  ).version;

  assertGeneratorOwned(readBundle(), installed);

  await regenerateOnce();
  const first = readBundle();
  const firstHash = sha256(first);
  assertGeneratorOwned(first, installed);

  await regenerateOnce();
  const second = readBundle();
  const secondHash = sha256(second);
  assertGeneratorOwned(second, installed);

  if (firstHash !== secondHash) {
    fail(`regeneration is not idempotent: ${firstHash} !== ${secondHash}`);
  }

  runShell(`"${process.execPath}" "${EXTRACT_BIN}" "${ROOT}"`);
  // extract-manifest calls Vite resolveConfig, which re-runs mcpPlugin. Repair
  // again so a Windows host cannot leave the collapsed npm:C:\ stub committed.
  await syncMcpSupabaseFunction(ROOT, productionImportMetaEnv({ root: ROOT, envDir: ROOT, envPrefix: "VITE_", base: "/" }));

  const dirty = gitDiff(["supabase/functions/mcp/index.ts", ".lovable/mcp/manifest.json"]);
  if (dirty) {
    fail(`regeneration left a dirty tree:\n${dirty}`);
  }

  console.log("mcp-edge-validate: bundle regeneration is idempotent and generator-owned");
  console.log(`mcp-edge-validate: bundle sha256 ${firstHash}`);
}

function typecheckMcpSource() {
  runShell("bunx tsc --noEmit -p tsconfig.app.json");
}

function runMcpAndMoversTests() {
  runShell(
    "bunx vitest run src/lib/mcp/__tests__/get-market-movers.test.ts src/lib/markets/__tests__/movers-integrity.test.ts src/lib/pre-market/__tests__/mcp-unchanged.test.ts",
  );
}

const bundleOnly = process.argv.includes("--bundle-only");
if (!bundleOnly) {
  typecheckMcpSource();
  runMcpAndMoversTests();
}
await validateBundle();
