/**
 * Windows-safe re-emit of the @lovable.dev/mcp-js Supabase function.
 *
 * The official plugin builds a wrapper `import mcp from ${absolutePath}`. On
 * POSIX that path starts with `/` and esbuild bundles it. On Windows it is
 * `C:\...`, which the plugin's "bare specifier" rule rewrites to `npm:C:\...`
 * and the emitted function collapses to a stub.
 *
 * This helper uses the same esbuild flags, banner, npm: pinning, and
 * production `import.meta.env` inlining as the official plugin, with a
 * project-relative import so the graph is bundled on every OS. Ownership
 * stays with the AUTO-GENERATED banner; files without it are not touched.
 */
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { loadEnv } from "vite";

const require = createRequire(import.meta.url);
const { build } = require(join(
  dirname(fileURLToPath(import.meta.url)),
  "../node_modules/@lovable.dev/mcp-js/node_modules/esbuild/lib/main.js",
));

export const GENERATED_BANNER =
  "// AUTO-GENERATED by @lovable.dev/mcp-js — do not edit. Regenerated by the Vite plugin.\n" +
  "// To take ownership, delete this banner line; the plugin then leaves the file alone.";

const DEFAULT_MCP_ENTRY = "src/lib/mcp/index.ts";
const DEFAULT_FUNCTIONS_DIR = "supabase/functions";
const DEFAULT_FUNCTION_NAME = "mcp";

function hasGeneratedBanner(content) {
  return content.replace(/\r\n/g, "\n").startsWith(GENERATED_BANNER);
}

function isCollapsedWindowsStub(content) {
  return (
    /import mcp from "npm:[A-Za-z]:[\\/]/.test(content) ||
    (hasGeneratedBanner(content) && !content.includes('name: "get_market_movers"'))
  );
}

function readProjectDependencyVersions(projectRoot) {
  try {
    const pkg = JSON.parse(readFileSync(join(projectRoot, "package.json"), "utf8"));
    return { ...pkg.peerDependencies, ...pkg.devDependencies, ...pkg.dependencies };
  } catch {
    return {};
  }
}

function npmSpecifierFor(bare, versions, mcpJsVersion) {
  const pkg = bare.startsWith("@") ? bare.split("/").slice(0, 2).join("/") : bare.split("/")[0];
  const subpath = bare.slice(pkg.length);
  if (pkg === "@lovable.dev/mcp-js") return `npm:${pkg}@${mcpJsVersion}${subpath}`;
  const range = versions[pkg];
  const version = range && /^[\dv^~>=]|^latest$/.test(range) ? range : undefined;
  return version ? `npm:${pkg}@${version}${subpath}` : `npm:${pkg}${subpath}`;
}

function externalizeBareAsNpm(versions, mcpJsVersion) {
  return {
    name: "lovable-mcp-externalize-bare-as-npm",
    setup(pluginBuild) {
      pluginBuild.onResolve({ filter: /.*/ }, (args) => {
        const p = args.path;
        if (p.startsWith(".") || p.startsWith("/")) return null;
        if (/^(npm|node|jsr|https?|data):/.test(p)) return { path: p, external: true };
        return { path: npmSpecifierFor(p, versions, mcpJsVersion), external: true };
      });
    },
  };
}

function importMetaEnvDefines(inlineEnv) {
  const env = inlineEnv ?? {};
  const defines = { "import.meta.env": JSON.stringify(env) };
  for (const [key, value] of Object.entries(env)) {
    if (/^[A-Za-z_$][\w$]*$/.test(key)) {
      defines[`import.meta.env.${key}`] = JSON.stringify(value);
    }
  }
  return defines;
}

export function productionImportMetaEnv(config) {
  return {
    ...loadEnv("production", config.envDir ?? config.root, config.envPrefix),
    MODE: "production",
    BASE_URL: config.base ?? "/",
    DEV: false,
    PROD: true,
    SSR: false,
  };
}

export async function emitMcpSupabaseFunction(projectRoot, inlineEnv) {
  const mcpJsVersion = JSON.parse(
    readFileSync(join(projectRoot, "node_modules/@lovable.dev/mcp-js/package.json"), "utf8"),
  ).version;
  const mcpEntryAbs = resolve(projectRoot, DEFAULT_MCP_ENTRY);
  const functionEntry = join(projectRoot, DEFAULT_FUNCTIONS_DIR, DEFAULT_FUNCTION_NAME, "index.ts");
  const mcpEntryRel = `./${relative(projectRoot, mcpEntryAbs).split(sep).join("/")}`;
  const versions = readProjectDependencyVersions(projectRoot);
  const wrapper = `import mcp from ${JSON.stringify(mcpEntryRel)};
import { createSupabaseHandler } from "@lovable.dev/mcp-js/stacks/supabase";
Deno.serve(createSupabaseHandler(mcp, { functionName: ${JSON.stringify(DEFAULT_FUNCTION_NAME)} }));
`;
  const result = await build({
    stdin: {
      contents: wrapper,
      resolveDir: projectRoot,
      sourcefile: "lovable-mcp-supabase-entry.ts",
      loader: "ts",
    },
    bundle: true,
    write: false,
    metafile: true,
    format: "esm",
    platform: "neutral",
    target: "esnext",
    absWorkingDir: projectRoot,
    logLevel: "silent",
    define: importMetaEnvDefines(inlineEnv),
    plugins: [externalizeBareAsNpm(versions, mcpJsVersion)],
  });
  const out = result.outputFiles[0]?.text ?? "";
  return `${GENERATED_BANNER}
// supabase function: ${DEFAULT_FUNCTION_NAME}
// Bundled from ${relative(projectRoot, mcpEntryAbs).split(sep).join("/")} by @lovable.dev/mcp-js.
` + out;
}

function writeIfChanged(file, content) {
  let existing;
  try {
    existing = readFileSync(file, "utf8");
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  if (existing !== undefined) {
    if (!hasGeneratedBanner(existing)) {
      throw new Error(
        `@lovable.dev/mcp-js: refusing to overwrite user-authored file at ${file}. Delete it or move it first.`,
      );
    }
    if (existing === content || existing.replace(/\r\n/g, "\n") === content) return false;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content, "utf8");
  return true;
}

export async function syncMcpSupabaseFunction(projectRoot, inlineEnv, { repairCollapsedOnly = false } = {}) {
  const functionEntry = join(projectRoot, DEFAULT_FUNCTIONS_DIR, DEFAULT_FUNCTION_NAME, "index.ts");
  let existing = "";
  try {
    existing = readFileSync(functionEntry, "utf8");
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
  if (repairCollapsedOnly && existing && !isCollapsedWindowsStub(existing)) {
    return false;
  }
  const code = await emitMcpSupabaseFunction(projectRoot, inlineEnv);
  return writeIfChanged(functionEntry, code);
}

export function mcpWindowsSafeEmitPlugin() {
  let projectRoot = process.cwd();
  let inlineEnv = {};
  const regenerate = async () => {
    await syncMcpSupabaseFunction(projectRoot, inlineEnv);
  };
  return {
    name: "mcp-windows-safe-emit",
    enforce: "post",
    async configResolved(config) {
      projectRoot = config.root;
      inlineEnv = productionImportMetaEnv(config);
      await regenerate();
    },
    async buildStart() {
      await regenerate();
    },
  };
}
