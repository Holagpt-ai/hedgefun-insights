/**
 * Scanner field registry — presentation, education, and availability only.
 *
 * This is not a data source. Unavailable fields stay registered so the UI can
 * explain them without fabricating values. Radar discovery/ranking is unchanged.
 */

export type ScannerFieldFormat =
  | "text"
  | "price"
  | "percent"
  | "volume"
  | "multiplier"
  | "datetime"
  | "enum"
  | "rank";

export type ScannerFieldCategory =
  | "identity"
  | "price"
  | "volume"
  | "range"
  | "catalyst"
  | "radar"
  | "fundamentals"
  | "triggers"
  | "time";

/**
 * available         — currently populated from a truthful source when present
 * source-dependent  — present only when the active source actually supplies it
 * unavailable       — registered placeholder; never synthesize a value
 */
export type ScannerFieldAvailability = "available" | "source-dependent" | "unavailable";

export interface ScannerFieldDefinition {
  id: string;
  label: string;
  shortLabel: string;
  description: string;
  whyItMatters: string;
  example?: string;
  format: ScannerFieldFormat;
  category: ScannerFieldCategory;
  sortable: boolean;
  filterable: boolean;
  defaultVisible: boolean;
  mobileVisible: boolean;
  tooltipEnabled: boolean;
  availability: ScannerFieldAvailability;
  /** Human-readable origin when useful for honesty copy. */
  source?: string;
}

