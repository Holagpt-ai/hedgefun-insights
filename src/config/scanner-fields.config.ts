const FIELD_BY_ID: ReadonlyMap<string, ScannerFieldDefinition> = new Map(
  SCANNER_FIELDS.map((field) => [field.id, field]),
);

export function getScannerField(id: string): ScannerFieldDefinition | undefined {
  return FIELD_BY_ID.get(id);
}

export function scannerFieldIds(): string[] {
  return SCANNER_FIELDS.map((field) => field.id);
}

export function tooltipEnabledScannerFields(): ScannerFieldDefinition[] {
  return SCANNER_FIELDS.filter((field) => field.tooltipEnabled);
}
