-- Isolated PostgreSQL bootstrap for Batch 190 staging integration tests.
-- Not a production migration. Provides roles + screener publication schema contracts.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

DO $roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    CREATE ROLE service_role NOLOGIN;
  END IF;
END;
$roles$;

GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON SCHEMA public TO postgres;

CREATE TABLE IF NOT EXISTS public.screener_results (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tab_id text NOT NULL,
  symbol text NOT NULL,
  company_name text,
  price numeric,
  change_percent numeric,
  volume numeric,
  avg_volume numeric,
  rvol numeric,
  float_shares numeric,
  gap_percent numeric,
  high_52w numeric,
  low_52w numeric,
  market_cap numeric,
  prior_session_volume numeric,
  volume_ratio_prior_session numeric,
  avg_volume_20d numeric,
  rvol_20d numeric,
  day_high numeric,
  day_low numeric,
  range_event text,
  provider_as_of timestamptz,
  sync_run_id uuid,
  updated_at timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS screener_results_tab_id_symbol_uidx
  ON public.screener_results (tab_id, symbol);

CREATE TABLE IF NOT EXISTS public.screener_feed_state (
  state_key text PRIMARY KEY,
  sync_run_id uuid NOT NULL,
  status text NOT NULL,
  synced_at timestamptz NOT NULL,
  provider_as_of_min timestamptz,
  provider_as_of_max timestamptz,
  rows_inserted integer NOT NULL,
  tab_counts jsonb NOT NULL,
  nhl_baseline_status text,
  tab_evaluation_evidence jsonb,
  updated_at timestamptz NOT NULL,
  CONSTRAINT screener_feed_state_key_current CHECK (state_key = 'current'),
  CONSTRAINT screener_feed_state_status_check CHECK (status IN ('available', 'empty')),
  CONSTRAINT screener_feed_state_rows_nonneg CHECK (rows_inserted >= 0)
);

ALTER TABLE public.screener_feed_state ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.screener_results FROM PUBLIC;
REVOKE ALL ON TABLE public.screener_feed_state FROM PUBLIC;
GRANT SELECT ON TABLE public.screener_results TO anon, authenticated;
GRANT ALL ON TABLE public.screener_results TO service_role;
GRANT SELECT ON TABLE public.screener_feed_state TO anon, authenticated;
GRANT ALL ON TABLE public.screener_feed_state TO service_role;
